#!/usr/bin/env node
/**
 * @fileoverview Event topology doc generator.
 *
 * Renders producer → event → consumer relationships from each module's `{context}.produces.ts` +
 * `{context}.subscriptions.ts` (auto-discovered, see ./lib/discover-module-events.mjs) into a
 * checked-in Markdown doc, so the topology shows up as a normal reviewable diff whenever a module's
 * manifest changes — instead of only being reconstructable by grepping every module.
 *
 * Usage: node ./scripts/generate-topology.mjs
 * Requires every module package to be built first (pnpm --filter @workspace/{context} build).
 */

import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { AllEvents } from '@workspace/types';
import { EventSubscriptionRegistry } from '@workspace/events';
import { discoverModuleEvents, findRepoRoot } from './lib/discover-module-events.mjs';

const NON_CONTEXT_ENTRIES = new Set(['index.ts', 'types.ts', 'shared.ts', 'outbox']);

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = findRepoRoot(__dirname);
const modules = await discoverModuleEvents();

// Same source buildContextBoundaryZones (packages/configs/eslint/base.ts) reads —
// every bounded context that has a schema, whether or not its module package
// exists yet. Diffed against `modules` (below) so the "still placeholder"
// list in the doc never goes stale as new modules get built.
const schemaDir = join(repoRoot, 'packages', 'server', 'ports', 'src', 'database', 'schema');
const allContexts = existsSync(schemaDir)
  ? readdirSync(schemaDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && !NON_CONTEXT_ENTRIES.has(e.name))
      .map((e) => e.name)
  : [];
const builtContexts = new Set(modules.map((m) => m.context));
const placeholderContexts = allContexts.filter((c) => !builtContexts.has(c));

const registry = new EventSubscriptionRegistry();
// `eventsSubscription` (a former 'workspace.*' catch-all in @workspace/events)
// was removed — audit's own 'workspace.*' subscription is the catch-all now
// (see apps/worker/src/events-routing.module.ts). Only the discovered module
// subscriptions feed the topology.
registry.registerMany([...modules.map((m) => m.subscriptions).filter((s) => s !== null)]);

// Map a matched EventSubscription back to the module context that declared it.
const contextBySubscriptionName = new Map();
for (const m of modules) {
  if (m.subscriptions) contextBySubscriptionName.set(m.subscriptions.name, m.context);
}

function producerFor(eventType) {
  return modules.find((m) => m.produces.includes(eventType))?.context ?? null;
}

function consumersFor(eventType) {
  return registry
    .getSubscribersFor(eventType)
    .map((s) => contextBySubscriptionName.get(s.name) ?? s.name);
}

const allEventTypes = Object.values(AllEvents).sort();
const rows = allEventTypes.map((eventType) => ({
  eventType,
  producer: producerFor(eventType),
  consumers: consumersFor(eventType),
}));

const withProducer = rows.filter((r) => r.producer);
const withoutProducer = rows.filter((r) => !r.producer);

const mermaidLines = ['flowchart LR'];
const declaredNodes = new Set();
for (const { eventType, producer, consumers } of withProducer) {
  const producerNode = `${producer}_p["${producer}"]`;
  if (!declaredNodes.has(producerNode)) {
    mermaidLines.push(`  ${producerNode}`);
    declaredNodes.add(producerNode);
  }
  for (const consumer of consumers) {
    if (consumer === '(transport)') continue;
    const consumerNode = `${consumer}_c["${consumer}"]`;
    mermaidLines.push(`  ${producerNode} -->|${eventType}| ${consumerNode}`);
  }
}

const tableRows = rows
  .map(
    (r) =>
      `| \`${r.eventType}\` | ${r.producer ?? '_none yet_'} | ${r.consumers.join(', ') || '_none_'} |`,
  )
  .join('\n');

const doc = `# Event Topology

Generated by \`pnpm --filter @workspace/events generate:topology\` from each module's
\`{context}.produces.ts\` + \`{context}.subscriptions.ts\`. Do not hand-edit — regenerate instead.

## Producer → consumer graph

Limited to events with a declared producer (the full catalog is in the table below) — most of the
${allEventTypes.length} catalog entries don't have an owning module yet (see "Coverage" below), and
diagramming all of them against audit's catch-all consumer wouldn't be legible.

\`\`\`mermaid
${mermaidLines.join('\n')}
\`\`\`

## Full catalog

| Event | Producer | Consumers |
| --- | --- | --- |
${tableRows}

## Coverage

- ${allEventTypes.length} events in the catalog, across ${modules.length} discovered module(s): ${modules.map((m) => m.context).join(', ')}.
- ${withProducer.length} have a declared producer (\`{context}.produces.ts\`); ${withoutProducer.length} don't yet — expected, since ${placeholderContexts.length ? `these bounded contexts (${placeholderContexts.join(', ')}) are` : 'no bounded context is'} still a placeholder with no module package built out.
- Every event shows at least one consumer today because \`auditSubscriptions\`
  (\`modules/audit\`, \`'workspace.*'\` — the audit trail, a real consumer of everything by design)
  is a full wildcard. This means \`check-event-coverage.mjs\` can't yet catch a genuinely orphaned
  event on its own; it becomes a meaningful signal once more modules subscribe selectively.
`;

const outDir = join(repoRoot, 'docs', 'architecture');
const outFile = join(outDir, 'events-topology.md');

if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
writeFileSync(outFile, doc);

console.log(`[generate-topology] Wrote ${outFile} (${allEventTypes.length} events, ${modules.length} modules).`);
