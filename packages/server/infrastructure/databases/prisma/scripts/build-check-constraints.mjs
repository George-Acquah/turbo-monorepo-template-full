/**
 * @fileoverview Workspace Constraint Generator
 *
 * Reads the typed CHECK-constraint registry from @workspace/constants
 * (DatabaseConstraintRegistry, built from the /// @check(...) doc-comments in
 * the 13 bounded-context .prisma files) and generates a single, idempotent
 * PostgreSQL migration file: CHECK constraints + the append-only audit-table
 * REVOKE lockdown.
 *
 * STEPS:
 * 1. Import @workspace/constants (must be built — `pnpm --filter
 *    @workspace/constants build` — since this is a plain Node ESM import of
 *    its compiled dist output, not a TS/ts-node run).
 * 2. Render each CheckConstraintSpec into idempotent SQL (DROP + ADD).
 * 3. Render guarded REVOKE UPDATE/DELETE for append-only audit tables.
 * 4. Write to a single fixed (non-timestamped) migration folder, overwritten
 *    on every run — regenerating never spawns new migration folders.
 *
 * This script only WRITES the SQL file. It never runs `prisma migrate`; per
 * repo rules, applying migrations is a separate, explicitly-approved step.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const migrationsDir = resolve(__dirname, '..', 'prisma', 'migrations');

// Fixed folder name: regenerating overwrites the same migration.sql instead
// of spawning a new timestamped folder (and a new _prisma_migrations entry)
// on every run.
const timestamp = new Date()
  .toISOString()
  .replace(/[-:TZ.]/g, '')
  .slice(0, 14);

const MIGRATION_FOLDER = `${timestamp}_check_constraints_and_audit_lock`;

// [Step 1] Load the typed constraint registry.
let constants;
try {
  constants = await import('@workspace/constants');
} catch (err) {
  console.error(
    '[build-check-constraints] Could not import @workspace/constants.\n' +
      "  Most likely cause: the package hasn't been built yet.\n" +
      '  Fix: pnpm --filter @workspace/constants build\n\n' +
      `  Original error: ${err.message}`,
  );
  process.exitCode = 1;
  throw err;
}

const { DatabaseConstraintRegistry, AppendOnlyTables, AppDatabaseRoles } = constants;

if (!DatabaseConstraintRegistry) {
  throw new Error(
    '[build-check-constraints] @workspace/constants did not export DatabaseConstraintRegistry.',
  );
}

// [Step 2] Render CHECK constraints (idempotent DROP + ADD).
const sqlLines = [];
sqlLines.push('-- ─────────────────────────────────────────────────────────────────────────────');
sqlLines.push('-- Workspace — CHECK constraints + append-only audit lockdown.');
sqlLines.push('-- Generated by scripts/build-check-constraints.mjs from @workspace/constants');
sqlLines.push('-- (DatabaseConstraintRegistry). DO NOT EDIT BY HAND — re-run the script instead.');
sqlLines.push('-- ─────────────────────────────────────────────────────────────────────────────');
sqlLines.push('');

let checkCount = 0;
for (const spec of DatabaseConstraintRegistry) {
  if (!spec.table || (!spec.column && !spec.expression)) continue;

  const constraintName = spec.name ?? `chk_${spec.table}_${spec.column}`;
  sqlLines.push(
    `ALTER TABLE "${spec.schema}"."${spec.table}" DROP CONSTRAINT IF EXISTS "${constraintName}";`,
  );

  let checkExpr;
  if (spec.expression) {
    checkExpr = spec.expression.trim();
  } else if (spec.values) {
    const valueList = spec.values.map((v) => `'${v.replace(/'/g, "''")}'`).join(', ');
    checkExpr = `"${spec.column}" IN (${valueList})`;
  } else {
    const conditions = [];
    const isNumber = spec.type === 'number';
    if (spec.minLength != null) {
      conditions.push(
        isNumber ? `"${spec.column}" >= ${spec.minLength}` : `LENGTH("${spec.column}") >= ${spec.minLength}`,
      );
    }
    if (spec.maxLength != null) {
      conditions.push(
        isNumber ? `"${spec.column}" <= ${spec.maxLength}` : `LENGTH("${spec.column}") <= ${spec.maxLength}`,
      );
    }
    if (conditions.length === 0) continue;
    checkExpr = conditions.join(' AND ');
  }

  sqlLines.push(
    `ALTER TABLE "${spec.schema}"."${spec.table}" ADD CONSTRAINT "${constraintName}" CHECK (${checkExpr});`,
    '',
  );
  checkCount += 1;
}

// [Step 3] Render the append-only audit-table REVOKE lockdown. Guarded with
// IF EXISTS(pg_roles) since no migration provisions workspace_api /
// workspace_worker yet — this makes the migration safe to apply in any
// order relative to role provisioning, and self-activating once roles exist.
sqlLines.push('-- ─────────────────────────────────────────────────────────────────────────────');
sqlLines.push('-- Append-only lockdown: revoke UPDATE/DELETE on audit tables from app roles.');
sqlLines.push('-- Guarded — no-ops safely until the app DB roles are provisioned.');
sqlLines.push('-- ─────────────────────────────────────────────────────────────────────────────');
sqlLines.push('');

const appRoles = [AppDatabaseRoles.API, AppDatabaseRoles.WORKER];
let revokeCount = 0;
for (const { schema, table } of AppendOnlyTables ?? []) {
  for (const role of appRoles) {
    sqlLines.push(
      'DO $$',
      'BEGIN',
      `  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '${role}') THEN`,
      `    REVOKE UPDATE, DELETE ON "${schema}"."${table}" FROM "${role}";`,
      '  END IF;',
      'END $$;',
      '',
    );
    revokeCount += 1;
  }
}

// [Step 4] Write to the fixed migration folder (overwrite, not append).
const targetDir = join(migrationsDir, MIGRATION_FOLDER);
mkdirSync(targetDir, { recursive: true });
const sqlPath = join(targetDir, 'migration.sql');
writeFileSync(sqlPath, sqlLines.join('\n') + '\n', 'utf8');

console.log(
  `[build-check-constraints] wrote ${checkCount} CHECK constraints + ${revokeCount} guarded REVOKE statements → ${sqlPath}`,
);
console.log(
  '[build-check-constraints] This file is generated only — it is NOT applied automatically.\n' +
    '  Review it, then apply via `pnpm --filter @workspace/prisma prisma:migrate:dev` (or `migrate:deploy`)\n' +
    '  once you are ready, and only after the base tables exist.',
);
